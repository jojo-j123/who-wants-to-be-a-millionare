'use strict';
/**
 * Packs the server-side modules into a single self-contained Vercel function.
 *
 * Same reason as build-vercel-bundle.js: an API upload that cannot carry the
 * whole tree. Embedding the modules (compressed, checksummed) inside the
 * function file means there is nothing for Vercel's dependency tracer to
 * resolve — no lib/ directory has to survive the trip.
 *
 *   node scripts/build-vercel-function.js
 */
const fs = require('fs');
const path = require('path');
const zlib = require('zlib');
const crypto = require('crypto');

const ROOT = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');
const compact = p => JSON.stringify(JSON.parse(read(p)));

// Fallback store credentials for a deployment that cannot set env vars.
// Absent is fine: the function then runs in ephemeral demo mode.
const readConfig = () => {
  try { return compact('config/store.json'); } catch (_) { return '{}'; }
};

const modules = {
  // The real entry point, embedded rather than restated: every require() it
  // makes ("../lib/game", "../data/questions.json", "url") already lands on a
  // bundled name or a Node built-in through the resolve() shim below. Keeping
  // one copy is the point — a hand-written twin drifts the moment either side
  // is edited.
  'entry': read('api/[[...path]].js'),
  'game': read('lib/game.js'),
  'api': read('lib/api.js'),
  'routes': read('lib/routes.js'),
  'kv': read('lib/kv.js'),
  'kv-upstash': read('lib/kv-upstash.js'),
  'supabase': read('lib/supabase.js'),
  'store-config': readConfig(),
  'defaults': read('lib/defaults.js'),
  'questions': compact('data/questions.json'),
  'settings': compact('data/settings.json'),
  'package': JSON.stringify({ version: require(path.join(ROOT, 'package.json')).version })
};

const json = Buffer.from(JSON.stringify(modules));
const br = zlib.brotliCompressSync(json, {
  params: {
    [zlib.constants.BROTLI_PARAM_QUALITY]: 11,
    [zlib.constants.BROTLI_PARAM_SIZE_HINT]: json.length
  }
});
const b64 = br.toString('base64');
const sha = crypto.createHash('sha256').update(br).digest('hex');

const handler = `
module.exports = load('entry');
`;

const out = `'use strict';
/**
 * Vercel serverless entry point - self-contained build.
 *
 * The server modules (lib/*.js and the seed data) are embedded below as one
 * brotli'd, checksummed blob and evaluated at cold start. That keeps the
 * function independent of any other file surviving the upload, which is what
 * lets it be deployed through an API that can only carry a small tree.
 *
 * Generated by scripts/build-vercel-function.js - do not edit by hand.
 */
const zlib = require('zlib');
const crypto = require('crypto');

const BUNDLE_SHA256 = '${sha}';
const BUNDLE = '${b64}';

const packed = Buffer.from(BUNDLE, 'base64');
const actual = crypto.createHash('sha256').update(packed).digest('hex');
if (actual !== BUNDLE_SHA256) {
  throw new Error('Embedded server bundle is corrupted (sha256 ' + actual + ', expected ' + BUNDLE_SHA256 + ').');
}
const SOURCES = JSON.parse(zlib.brotliDecompressSync(packed).toString('utf8'));

const cache = Object.create(null);

/** Resolves the bundled module names the packed sources require of each other. */
function resolve(spec) {
  const base = String(spec).replace(/^.*\\//, '').replace(/\\.(js|json)$/, '');
  return Object.prototype.hasOwnProperty.call(SOURCES, base) ? base : null;
}

function load(name) {
  const key = resolve(name);
  if (!key) return require(name); // a Node built-in
  if (cache[key]) return cache[key].exports;

  const mod = { exports: {} };
  cache[key] = mod;
  const src = SOURCES[key];

  if (key === 'questions' || key === 'settings' || key === 'package' || key === 'store-config') {
    mod.exports = JSON.parse(src);
    return mod.exports;
  }
  const fn = new Function('require', 'module', 'exports', '__filename', '__dirname', src);
  fn(load, mod, mod.exports, '/' + key + '.js', '/');
  return mod.exports;
}
${handler}`;

fs.mkdirSync(path.join(ROOT, 'vercel-bundle'), { recursive: true });
const dest = path.join(ROOT, 'vercel-bundle', 'function.js');
fs.writeFileSync(dest, out);

console.log('modules      :', Object.keys(modules).join(', '));
console.log('sources      :', json.length, 'bytes');
console.log('brotli       :', br.length, 'bytes');
console.log('function.js  :', out.length, 'chars (~' + Math.round(out.length / 4) + ' tokens)');
console.log('sha256       :', sha);
